# 1-dimensional array
array_1d = [1, 2, 3, 4, 5]

# 2-dimensional array
array_2d = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9]
]

# 3-dimensional array
array_3d = [
    [
        [1, 2],
        [3, 4]
    ],
    [
        [5, 6],
        [7, 8]
    ]
]

print("1D array:", array_1d)
print("2D array:", array_2d)
print("3D array:", array_3d)
